function normalize(value: string): string {
  return (value || '').toLowerCase().replace(/[^a-z0-9]/g, '')
}

export function coursesForSchool(school?: string | null): string[] {
  if (!school) return []
  const canon = SCHOOL_COURSES[school] ? school : ALIASES[normalize(school)]
  if (!canon) return []
  return SCHOOL_COURSES[canon] || []
}

export function schoolHasCourses(school?: string | null): boolean {
  return coursesForSchool(school).length > 0
}
